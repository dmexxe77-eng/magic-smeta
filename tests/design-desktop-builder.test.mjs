import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

test('desktop builder reads the native app behind the preview host and retains legacy build support', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'zamer-desktop-build-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  // Copy the builders and validation dependencies so every generated path is local
  // to this fixture; production working data and generated engines are never used.
  for (const filename of [
    'scripts/build-desktop.mjs',
    'scripts/build-online-data.mjs',
    'scripts/desktop-identities.mjs',
    'scripts/desktop-project-snapshots.mjs',
    'src/desktop/desktop-storage.js',
    'src/desktop/nomenclature-identity.js',
    'src/desktop/project-catalog.js',
    'src/desktop/snapshot-images.js',
    'src/design-bridge/design-storage.js',
    'public/design/app.html',
    'public/design/index.html',
  ]) {
    const destination = path.join(root, filename);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(path.join(project, filename), destination);
  }
  fs.writeFileSync(path.join(root, 'package.json'), '{"type":"module"}');
  const original = '{"fixture":true}\n';
  const data = {
    version: 1,
    blocks: [{ id: 'canvas', title: 'Полотно' }, { id: 'main', title: 'Профиль' }],
    presets: { canvas: [], main: [] },
    nom: [], roomOpts: [], projects: [], estEd: {},
    migration: {
      sourceHash: crypto.createHash('sha256').update(original).digest('hex'),
      sourceFile: 'fixture.json',
      report: { parityOk: true, unavailablePhotos: [], images: [] },
    },
  };
  const source = path.join(root, 'online-src/working-data.json');
  fs.mkdirSync(path.dirname(source), { recursive: true });
  fs.writeFileSync(source, JSON.stringify(data));
  fs.writeFileSync(source + '.source.json', original);
  const run = () => spawnSync(process.execPath, ['scripts/build-desktop.mjs'], {
    cwd: root, encoding: 'utf8', timeout: 30000,
  });
  const generated = path.join(root, 'src/desktop/generated/mobile-engine.js');

  const current = run();
  assert.equal(current.status, 0, current.stderr || current.error?.message);
  const engine = fs.readFileSync(generated, 'utf8');
  assert.match(engine, /^\/\/ Generated by scripts\/build-desktop\.mjs from public\/design\/app\.html\./);
  assert.match(engine, /export \{ Component as MobileEngine,/);
  assert.equal(spawnSync(process.execPath, ['--check', generated], { encoding: 'utf8' }).status, 0);
  for (const filename of ['manrope-cyrillic.woff2', 'manrope-latin.woff2']) {
    assert.equal(fs.readFileSync(path.join(root, 'public/online', filename)).toString('ascii', 0, 4), 'wOF2');
  }
  assert.match(fs.readFileSync(path.join(root, 'public/online/main-data.js'), 'utf8'), /window\.MAGIC_MAIN=/);
  assert.equal(fs.readFileSync(source + '.source.json', 'utf8'), original);

  fs.copyFileSync(path.join(root, 'public/design/app.html'), path.join(root, 'public/design/index.html'));
  fs.unlinkSync(path.join(root, 'public/design/app.html'));
  const legacy = run();
  assert.equal(legacy.status, 0, legacy.stderr || legacy.error?.message);
  assert.match(fs.readFileSync(generated, 'utf8'), /^\/\/ Generated by scripts\/build-desktop\.mjs from public\/design\/index\.html\./);

  fs.writeFileSync(path.join(root, 'public/design/app.html'), '<!doctype html><title>Incomplete build</title>');
  const incomplete = run();
  assert.notEqual(incomplete.status, 0);
  assert.match(incomplete.stderr, /Build mobile first: npm run design/);
});
