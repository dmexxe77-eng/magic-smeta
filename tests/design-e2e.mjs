import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from 'playwright';

const base=process.env.DESIGN_URL||'http://127.0.0.1:5173/design/index.html';
const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'chrome',headless:true});
const dir='artifacts/design';fs.mkdirSync(dir,{recursive:true});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const name='E2E Защита пола';
try{
  await page.goto(base,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.__zamer);
  const seed=await page.evaluate(()=>JSON.stringify(window.MAGIC_MAIN));
  await page.getByTitle('Аккаунт',{exact:true}).click();
  await page.getByText('Редактор кнопок',{exact:true}).click();
  assert.doesNotMatch(await page.locator('body').innerText(),/ПАРАМЕТР КНОПКИ/);
  await page.getByRole('button',{name:'+ блок',exact:true}).click();
  await page.getByLabel('Название блока',{exact:true}).fill(name);
  await page.getByRole('button',{name:/Площадь с чертежа/}).click();
  await page.screenshot({path:dir+'/new-block.png'});
  await page.getByRole('button',{name:'Создать блок',exact:true}).click();
  const blockId=await page.evaluate(()=>window.__zamer.state.be.bid);
  assert.match(blockId,/^custom_/);
  await page.waitForFunction(id=>{const el=document.querySelector('[data-quantity-tab="'+id+'"]');if(!el)return false;const box=el.getBoundingClientRect();return box.x>=0&&box.right<=innerWidth;},blockId,{timeout:5000});
  const activeTab=await page.getByRole('button',{name,exact:true}).boundingBox();
  assert.ok(activeTab&&activeTab.x>=0&&activeTab.x+activeTab.width<=390,'newly created block tab is visible');
  await page.locator('input:visible').first().fill('Защита пола');
  await page.getByRole('button',{name:'+ Добавить',exact:true}).click();
  assert.doesNotMatch(await page.locator('body').innerText(),/^all\n0 позиций/m);
  await page.getByPlaceholder('Поиск по базе',{exact:true}).fill('Натяжка ПВХ потолка');
  await page.getByText('Натяжка ПВХ потолка',{exact:true}).last().click();
  await page.getByRole('button',{name:'Добавить в кнопку · 1',exact:true}).click();
  await page.getByText('Количество блока',{exact:true}).last().click();
  await page.getByText('Ввести отдельно',{exact:true}).last().click();
  assert.equal(await page.evaluate(()=>window.__zamer.beVals().beItems[0].srcLabel),'Ввести отдельно');
  await page.getByText('Ввести отдельно',{exact:true}).last().click();
  await page.getByText('Количество блока',{exact:true}).last().click();
  await page.screenshot({path:dir+'/editor.png'});
  const fixture=await page.evaluate(({blockId})=>{
    const app=window.__zamer,original=app.state.projects.find(p=>p.rooms.length),originalRoom=original.rooms[0];
    const room={...originalRoom,id:'e2e_room',name:'Тестовая комната',on:true,v:[[0,0],[4,0],[4,3],[0,3]],holes:[],canvas:{pid:null,off:{}},main:{pid:null,off:{}},extra:[],light:[],track:[],curtain:[],other:[],extraItems:[],opts:{},optQ:{}};
    const project={...original,id:'e2e_project',name:'Проверка пресетов',status:'estimate',rooms:[room]};
    const pid=app.state.be.pid;
    app.setState({projects:[project],screen:'calc',curId:project.id,tab:room.id,sheet:null});
    return{pid,price:app.calcVals().blocks.find(b=>b.id===blockId).unit};
  },{blockId});
  const add=page.getByRole('button',{name:'+ Добавить '+name.toLocaleLowerCase('ru'),exact:true});
  await add.click();
  await add.click();
  const first=page.getByLabel('Количество блока '+name+' 1',{exact:true});
  const second=page.getByLabel('Количество блока '+name+' 2',{exact:true});
  assert.equal(await first.inputValue(),'12');
  assert.equal(await second.inputValue(),'12');
  await first.fill('3');await first.press('Tab');
  assert.equal(await second.inputValue(),'12');
  const rows=page.getByLabel('Количество позиции Натяжка ПВХ потолка',{exact:true});
  assert.equal(await rows.nth(0).inputValue(),'3');
  assert.equal(await rows.nth(1).inputValue(),'12');
  await rows.nth(0).fill('5');await rows.nth(0).press('Tab');
  await first.fill('4');await first.press('Tab');
  assert.equal(await rows.nth(0).inputValue(),'5','row override must survive primary quantity edits');
  await second.fill('0');await second.press('Tab');
  assert.equal(await second.inputValue(),'0','zero is an explicit value');
  await page.evaluate(()=>window.__zamer.saveDesign());
  await page.reload({waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.__zamer);
  assert.equal(await page.evaluate(()=>window.__zamer.state.projects.length),1);
  const persisted=await page.evaluate(blockId=>{
    const app=window.__zamer,room=app.state.projects[0].rooms[0];
    app.openCalc('e2e_project');
    return room[blockId];
  },blockId);
  assert.equal(persisted[0].qty,4);assert.equal(persisted[1].qty,0);
  assert.equal(persisted[0].iq['Натяжка ПВХ потолка'],5);
  assert.equal(await page.getByLabel('Количество блока '+name+' 1',{exact:true}).inputValue(),'4');
  await page.screenshot({path:dir+'/calculator.png'});
  await page.evaluate(({blockId,pid})=>window.__zamer.go('btnEd',{be:{bid:blockId,pid,from:'calc'}}),{blockId,pid:fixture.pid});
  await page.getByRole('button',{name:'Настроить блок',exact:true}).click();
  await page.getByRole('button',{name:/Вводится вручную/}).click();
  await page.getByRole('button',{name:'шт',exact:true}).click();
  await page.getByRole('button',{name:'Сохранить блок',exact:true}).click();
  await page.evaluate(()=>window.__zamer.openCalc('e2e_project'));
  await page.getByRole('button',{name:'+ Добавить '+name.toLocaleLowerCase('ru'),exact:true}).click();
  const third=page.getByLabel('Количество блока '+name+' 3',{exact:true});
  assert.equal(await third.inputValue(),'');
  const definitions=await page.evaluate(blockId=>window.__zamer.state.projects[0].rooms[0][blockId].map(i=>i.qdef),blockId);
  assert.deepEqual(definitions.map(d=>d.unit),['м²','м²','шт']);
  await third.fill('7,5');
  const plus=third.locator('..').getByRole('button',{name:'+',exact:true});
  await plus.click();
  assert.equal(await third.inputValue(),'8,5','first stepper click after typing must be applied');
  // Clear a manual row back to a true missing value, then check its independent sibling.
  await rows.nth(0).fill('');await rows.nth(0).press('Tab');
  assert.equal(await rows.nth(0).inputValue(),'4');
  assert.equal(await page.evaluate(()=>JSON.stringify(window.MAGIC_MAIN)),seed,'seed must stay immutable');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390,'no phone horizontal overflow');
  // Built-in area/manual values and apply-all settings retain quantities in other rooms.
  await page.evaluate(()=>{
    const app=window.__zamer,p=app.state.projects[0],r=p.rooms[0];
    const second={...JSON.parse(JSON.stringify(r)),id:'e2e_room_2',name:'Вторая комната',canvas:{pid:null,qtyO:8,iq:{'Натяжка ПВХ потолка':6},off:{}}};
    app.setState({projects:[{...p,rooms:[r,second]}],screen:'calc',tab:r.id});
  });
  await page.getByRole('button',{name:'MSD Evolution',exact:true}).click();
  const area=page.getByLabel('Количество блока Полотно 1',{exact:true});
  await area.fill('9');await area.press('Tab');
  await page.getByText('Ко всем',{exact:true}).first().click();
  const spread=await page.evaluate(()=>window.__zamer.state.projects[0].rooms.map(r=>r.canvas));
  assert.equal(spread[0].pid,spread[1].pid);
  assert.equal(spread[1].qtyO,8);
  assert.equal(spread[1].iq['Натяжка ПВХ потолка'],6);
  await area.fill('0');await area.press('Tab');
  assert.equal(await area.inputValue(),'0');
  await area.fill('');await area.press('Tab');
  assert.equal(await area.inputValue(),'12');
  assert.deepEqual(errors,[]);
  console.log('PASS: custom source/unit creation, nomenclature, row source switching, geometric quantities, independent cards, final row override, zero, reload, definition snapshots, manual stepper, immutable seed, 390px layout.');
}finally{
  await context.close();await browser.close();
}
